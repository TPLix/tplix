<?php
use Tplix\Tplix;
use Tplix\Template;
use Tplix\Security;
use Tplix\Plugins;

class TplixCompileDynamic
{
    public function call(array $tokens = []): string
    {
        // Get the current template variables
        $tplix = Tplix::getInstance();
        $current_scope = $tplix->getTemplateVars();
        $getDir = $tplix->getDir();
        $getSessionId = $tplix->getSessionId();
        $tplix->dynamicFileCount++;
        $dir = rtrim($getDir, '/') . '/dynamic/';
        if (!is_dir($dir)) mkdir($dir, 0777, true);        
        // Generate PHP code from the validated tokens
        $compiled_php_string = '';
        foreach ($tokens as $token)
        {
            $compiled_php_string .= Template::compileTokenToPhp($token);
        }
        // Validate the generated code snippet against the same rules
        // used for the main compiled template (optional but adds extra safety)
        // Security::validateCompiledCode($compiled_php_string); // Might throw exception if blacklist matches

        // Create a unique temporary file path
        $tmpFile = $dir.'tplix_'.$getSessionId.$tplix->dynamicFileCount.".php";
        if ($tmpFile === false) {
             throw new \RuntimeException("Could not create temporary file for dynamic block.");
        }
        // Write the validated PHP code to the temporary file
        $bytes_written = file_put_contents($tmpFile, $compiled_php_string, LOCK_EX);
        if ($bytes_written === false || $bytes_written !== strlen($compiled_php_string)) {
             unlink($tmpFile); // Clean up on write failure
             throw new \RuntimeException("Could not write to temporary file for dynamic block.");
        }
        // Start output buffering to capture the output of the included code
        ob_start();
        // Extract the current scope variables into the local scope
        // This makes variables like $values, $rate available to the included code
        extract($current_scope, EXTR_SKIP);
        // Include the temporary PHP file
        // Because the code inside was generated from validated tokens,
        // this is safer than arbitrary code injection, though still using 'include'.
        include $tmpFile;
        // Get the output generated by the included code
        $result = ob_get_contents();
        ob_end_clean(); // Clean up the output buffer
        // Immediately delete the temporary file after execution
        //unlink($tmpFile);
        // Note: If the included code modified variables (e.g., via {math assign}),
        // those changes are local to the include scope and won't affect $current_scope here.
        // If updates to the parent scope are needed, a different mechanism would be required,
        // potentially involving capturing variable assignments from the output buffer
        // or returning variable changes from the included script,
        // which adds significant complexity.
        return $result;
    }
    public function PluginCall($name="",$args=[],$loopNo=0)
    {
       return Plugins::call($name,$args,$loopNo);
    }    
}